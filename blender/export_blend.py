"""Save the finished character as one .blend: body, eyes, teeth, hair, clothes and the pistol,
with every motion clip stored as an action on the rig (the pistol routine is active).

blender -b --factory-startup --python blender/export_blend.py -- build/realistic_human.blend
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bpy  # noqa: E402
import numpy as np  # noqa: E402

import anim  # noqa: E402
import character  # noqa: E402
import clothes  # noqa: E402
import common as C  # noqa: E402
import hair  # noqa: E402
import pistol_clip  # noqa: E402  (re-uses its pistol keying; importing it does not render)
from rh import motions  # noqa: E402
from rh.pose import Skeleton  # noqa: E402

README = """REAL: a human built from scratch in Blender (https://github.com/SubToFeralsloth11/realistic-human)

Everything here was generated by the Python in that repository: no scans, downloads or mocap.

Animations: select the armature 'Rig', open the Action editor and pick an action:
  idle, walk, run, jump, backflip, crouch, punch, fall, shot   (character only)
  pistol   draw from the right front pocket, three shots, reload, put it back (active; the
           pistol, magazines, casings and muzzle flash are keyed to match this one only)
Set the scene frame range to the action's length (Action > Manual Frame Range is set on each).

Render: Cycles for stills (skin uses random-walk subsurface, hair uses the Chiang model);
EEVEE works too: hair and corneas carry separate EEVEE outputs.
"""


def main():
    out = C.args()[0]
    C.reset_scene()
    rig, body, eyes = character.build_character(os.path.join(C.BUILD, "human.npz"))
    hair.load_hair(os.path.join(C.BUILD, "hair.npz"), parent=rig, parent_bone="head")
    garments = clothes.load_clothes(rig=rig, body=body)
    skel = Skeleton(os.path.join(C.BUILD, "rig.json"))
    for name, fn in motions.CLIPS.items():
        frames, _ = fn(skel)
        fr = np.arange(1, len(frames) + 1)
        anim.key_rig(rig, fr, [f.quats for f in frames], [f.root_loc for f in frames], name=name)
        act = rig.animation_data.action
        act.use_fake_user = True
        act.use_frame_range = True
        act.frame_start, act.frame_end = 1, len(frames)
    n, _ = pistol_clip.setup_pistol_scene(rig, skel, garments)
    act = rig.animation_data.action
    act.use_fake_user = True
    act.use_frame_range = True
    act.frame_start, act.frame_end = 1, n
    scene = bpy.context.scene
    scene.frame_start, scene.frame_end = 1, n
    scene.render.fps = motions.FPS
    anim.outdoor_stage(sun_elev=34.0, sun_az=anim.key_light_azimuth((1.55, -2.75)), strength=0.85)
    anim.follow_camera("Cam", np.arange(1, n + 1), [np.array([0.0, -0.15, 1.24])] * n, (1.55, -2.75, 0.12), lens=40)
    C.setup_cycles(samples=128, res=(1920, 1080))
    txt = bpy.data.texts.new("README")
    txt.write(README)
    bpy.ops.wm.save_as_mainfile(filepath=os.path.abspath(out), compress=True)
    print("SAVED", out, os.path.getsize(out) // (1 << 20), "MB")


main()
